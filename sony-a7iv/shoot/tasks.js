// shot.A — разбор снимка (см. analyse в app.js), shot.st — настройки, shot.res — экспозиция,
// shot.face — средняя яркость лица на снимке (0…1, sRGB) или null, если лица нет в кадре.
// setup — стартовые настройки камеры: с них задачу ещё нужно решить.
import * as O from './optics.js?v=3';

const faceOk = (s, lo = 0.33, hi = 0.72) => {
  if (s.face == null) return { ok: false, text: 'Лицо не попало в кадр.' };
  const ok = s.face >= lo && s.face <= hi;
  return { ok, text: ok ? 'Лицо проэкспонировано нормально.' : s.face < lo ? `Лицо слишком тёмное (яркость ${Math.round(s.face * 100)}%).` : `Лицо пересвечено (яркость ${Math.round(s.face * 100)}%).` };
};
const sharp = (s) => ({ ok: s.A.subjSharp, text: s.A.subjSharp ? `${cap(s.A.subjName)} в зоне резкости.` : `${cap(s.A.subjName)} не в фокусе: резко ${O.fmtDist(s.A.d.near)} – ${O.fmtDist(s.A.d.far)}.` });
const noShake = (s) => ({ ok: s.A.shake < 1.5, text: s.A.shake < 1.5 ? 'Без шевелёнки.' : `Шевелёнка: выдержка ${O.fmtShutter(s.res.t)} слишком длинная для съёмки с рук.` });
const cap = (t) => t[0].toUpperCase() + t.slice(1);

